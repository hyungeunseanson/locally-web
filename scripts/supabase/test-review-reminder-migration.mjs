import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

import { PGlite } from '@electric-sql/pglite';

const db = new PGlite();
const guest = '11111111-1111-4111-8111-111111111111';
const host = '22222222-2222-4222-8222-222222222222';

await db.exec(`
  CREATE ROLE anon;
  CREATE ROLE authenticated;
  CREATE ROLE service_role BYPASSRLS;
  CREATE TABLE public.experiences (id bigint PRIMARY KEY, host_id uuid, title text, duration integer);
  CREATE TABLE public.bookings (id text PRIMARY KEY, user_id uuid, experience_id bigint, status text, date date, time text);
  CREATE TABLE public.notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL, type text NOT NULL, title text NOT NULL,
    message text NOT NULL, link text, is_read boolean DEFAULT false,
    booking_id text, created_at timestamptz DEFAULT now()
  );
  CREATE TABLE public.reviews (booking_id text PRIMARY KEY);
  CREATE TABLE public.guest_reviews (booking_id text PRIMARY KEY);
  GRANT USAGE ON SCHEMA public TO service_role;
  GRANT SELECT, INSERT ON ALL TABLES IN SCHEMA public TO service_role;
  GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO service_role;
  CREATE UNIQUE INDEX uq_notifications_review_request_booking_id ON public.notifications (booking_id)
    WHERE type = 'review_request' AND booking_id IS NOT NULL;
  CREATE UNIQUE INDEX uq_notifications_guest_review_request_booking_id ON public.notifications (booking_id)
    WHERE type = 'guest_review_request' AND booking_id IS NOT NULL;
  CREATE FUNCTION public.create_experience_review_atomic(text,uuid,bigint,integer,text)
    RETURNS integer LANGUAGE sql AS 'SELECT 1';
  CREATE FUNCTION public.create_guest_review_with_notification_atomic(text,uuid,integer,text,text,text)
    RETURNS integer LANGUAGE sql AS 'SELECT 1';
`);

const migration = await readFile('supabase/migrations/20260923084232_one_time_review_request_reminders.sql', 'utf8');
await db.exec(migration);

for (const role of ['public', 'anon', 'authenticated', 'service_role']) {
  const { rows } = await db.query(
    `SELECT has_function_privilege($1, 'public.claim_due_review_request_reminders(integer)', 'EXECUTE') AS allowed`,
    [role]
  );
  assert.equal(rows[0].allowed, role === 'service_role', `${role} execute grant`);
}

await db.query(`INSERT INTO public.experiences VALUES (1, $1, 'Review fixture', 2)`, [host]);
for (const [id, status, time] of [
  ['both', 'completed', '09:00'],
  ['guest-reviewed', 'completed', '09:00'],
  ['host-reviewed', 'completed', '09:00'],
  ['cancelled', 'cancelled', '09:00'],
  ['invalid-time', 'completed', '26:00'],
  ['before-24h', 'completed', '09:00'],
]) {
  await db.query(`INSERT INTO public.bookings VALUES ($1, $2, 1, $3, '2026-09-20', $4)`, [id, guest, status, time]);
  for (const [type, user] of [['review_request', guest], ['guest_review_request', host]]) {
    await db.query(`
      INSERT INTO public.notifications (user_id, type, title, message, link, booking_id, created_at)
      VALUES ($1, $2, 'Initial', 'Initial', '/review', $3,
        now() - CASE WHEN $3 = 'before-24h' THEN interval '23 hours' ELSE interval '25 hours' END)
    `, [user, type, id]);
  }
}
await db.exec(`INSERT INTO public.reviews VALUES ('guest-reviewed'); INSERT INTO public.guest_reviews VALUES ('host-reviewed');`);

const claim = async () => (await db.query(`SELECT booking_id, reminder_type FROM public.claim_due_review_request_reminders(50) ORDER BY booking_id, reminder_type`)).rows;
const first = await claim();
assert.deepEqual(first, [
  { booking_id: 'both', reminder_type: 'guest_review_request_reminder' },
  { booking_id: 'both', reminder_type: 'review_request_reminder' },
  { booking_id: 'guest-reviewed', reminder_type: 'guest_review_request_reminder' },
  { booking_id: 'host-reviewed', reminder_type: 'review_request_reminder' },
]);
assert.deepEqual(await claim(), [], 'rerun must claim zero');

await db.exec(`
  UPDATE public.notifications SET created_at = now() - interval '24 hours 1 second'
  WHERE booking_id = 'before-24h' AND type IN ('review_request', 'guest_review_request');
`);
assert.equal((await claim()).length, 2, 'after 24 hours each role is independent');

for (const type of ['review_request_reminder', 'guest_review_request_reminder']) {
  await assert.rejects(db.query(`
    INSERT INTO public.notifications (user_id, type, title, message, booking_id)
    VALUES ($1, $2, 'duplicate', 'duplicate', 'both')
  `, [type === 'review_request_reminder' ? guest : host, type]),
  /duplicate key value violates unique constraint/);
}

const concurrent = await Promise.allSettled([1, 2].map(() => db.query(`
  INSERT INTO public.notifications (user_id, type, title, message, booking_id)
  VALUES ($1, 'review_request_reminder', 'race', 'race', 'race-booking')
`, [guest])));
assert.deepEqual(concurrent.map((result) => result.status).sort(), ['fulfilled', 'rejected']);

const counts = (await db.query(`
  SELECT booking_id, type, count(*)::integer AS count
  FROM public.notifications
  WHERE type IN ('review_request_reminder', 'guest_review_request_reminder')
  GROUP BY booking_id, type ORDER BY booking_id, type
`)).rows;
assert.ok(counts.every((row) => row.count === 1));

// Reviewed requests must be filtered before LIMIT, or the oldest 50 would
// permanently starve a later eligible reminder.
for (let index = 0; index < 51; index += 1) {
  const bookingId = `reviewed-old-${index}`;
  await db.query(`INSERT INTO public.bookings VALUES ($1, $2, 1, 'completed', '2026-09-20', '09:00')`, [bookingId, guest]);
  await db.query(`INSERT INTO public.reviews VALUES ($1)`, [bookingId]);
  await db.query(`
    INSERT INTO public.notifications (user_id, type, title, message, booking_id, created_at)
    VALUES ($1, 'review_request', 'Initial', 'Initial', $2, now() - interval '30 hours')
  `, [guest, bookingId]);
}
await db.query(`INSERT INTO public.bookings VALUES ('after-reviewed', $1, 1, 'completed', '2026-09-20', '09:00')`, [guest]);
await db.query(`
  INSERT INTO public.notifications (user_id, type, title, message, booking_id, created_at)
  VALUES ($1, 'review_request', 'Initial', 'Initial', 'after-reviewed', now() - interval '25 hours')
`, [guest]);
const available = (await db.query(`SELECT booking_id FROM public.claim_due_review_request_reminders(1)`)).rows;
assert.deepEqual(available, [{ booking_id: 'after-reviewed' }]);
