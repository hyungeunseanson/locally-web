// Optional native PostgreSQL verification with two independent connections.
// Install embedded-postgres in an external temporary directory and supply its
// node_modules path as ADMIN_CHAT_NATIVE_MODULES. No remote DB URL is accepted.
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createServer } from 'node:net';

const modules = process.env.ADMIN_CHAT_NATIVE_MODULES;
if (!modules) throw new Error('Set ADMIN_CHAT_NATIVE_MODULES to an external embedded-postgres node_modules directory');
const require = createRequire(join(modules, '..', 'package.json'));
const EmbeddedPostgres = require('embedded-postgres').default;
const server = createServer();
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const port = server.address().port;
await new Promise(resolve => server.close(resolve));
const dir = await mkdtemp(join(tmpdir(), 'locally-admin-chat-native-'));
const pg = new EmbeddedPostgres({ databaseDir: join(dir, 'db'), user: 'postgres', password: 'local-test-only', port, persistent: false,
  postgresFlags: ['-c', 'listen_addresses=127.0.0.1', '-c', 'wal_level=logical'], onLog: () => {}, onError: () => {} });
const clients = [];
const guest = '11111111-1111-4111-8111-111111111111';
const admin = '33333333-3333-4333-8333-333333333333';
try {
  await pg.initialise(); await pg.start();
  for (let i = 0; i < 3; i++) { const client = pg.getPgClient('postgres', '127.0.0.1'); await client.connect(); clients.push(client); }
  const [setup, send, close] = clients;
  await setup.query(`
    CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;
    CREATE SCHEMA auth; CREATE TABLE auth.users(id uuid PRIMARY KEY,email text);
    CREATE TABLE public.users(id uuid PRIMARY KEY,role text);
    CREATE TABLE public.admin_whitelist(id bigint,email text);
    CREATE TABLE public.inquiries(id bigint PRIMARY KEY,user_id uuid,host_id uuid,type text,status text,content text,updated_at timestamptz DEFAULT now());
    CREATE TABLE public.inquiry_messages(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,inquiry_id bigint REFERENCES inquiries(id),sender_id uuid,content text,type text DEFAULT 'text',is_read boolean DEFAULT false,read_at timestamptz,created_at timestamptz DEFAULT now());
    GRANT ALL ON public.inquiries,public.inquiry_messages TO anon,authenticated,service_role;
    CREATE PUBLICATION supabase_realtime FOR TABLE public.inquiry_messages;
    INSERT INTO public.users VALUES ('${guest}','guest'),('${admin}','admin');
    INSERT INTO inquiries VALUES(1,'${guest}',null,'admin_support','open','question',clock_timestamp());
  `);
  const migration = await readFile('supabase/migrations/20261001170718_admin_message_monitoring_phase_1.sql', 'utf8');
  await setup.query(migration); await setup.query(migration);
  const publication = (await setup.query("SELECT tablename FROM pg_publication_tables WHERE pubname='supabase_realtime' ORDER BY tablename")).rows;
  assert.deepEqual(publication.map(r => r.tablename), ['inquiries', 'inquiry_messages']);

  const version = async () => (await setup.query("SELECT updated_at::text AS token FROM inquiries WHERE id=1")).rows[0].token;
  const status = async () => (await setup.query('SELECT status FROM inquiries WHERE id=1')).rows[0].status;
  const waiting = async (client) => {
    const deadline = Date.now() + 5000;
    while (Date.now() < deadline) {
      const row = (await setup.query('SELECT wait_event_type FROM pg_stat_activity WHERE pid=$1', [client.processID])).rows[0];
      if (row?.wait_event_type === 'Lock') return;
      await new Promise(resolve => setTimeout(resolve, 10));
    }
    throw new Error('Expected row-lock contention was not observed');
  };

  // Completion holds the lock first: customer INSERT waits, then reopens.
  await close.query('BEGIN');
  await close.query("UPDATE inquiries SET status='resolved' WHERE id=1");
  let insertFinished = false;
  const insert = send.query(`INSERT INTO inquiry_messages(inquiry_id,sender_id,content) VALUES(1,'${guest}','after completion')`).then(() => { insertFinished = true; });
  await waiting(send); assert.equal(insertFinished, false);
  await close.query('COMMIT'); await insert;
  assert.equal(await status(), 'open');

  // Customer holds the lock first: an old completion CAS waits and loses.
  const token = await version();
  await send.query('BEGIN');
  await send.query(`INSERT INTO inquiry_messages(inquiry_id,sender_id,content) VALUES(1,'${guest}','during completion')`);
  const completion = close.query("UPDATE inquiries SET status='resolved' WHERE id=1 AND updated_at=$1 RETURNING id", [token]);
  await waiting(close); await send.query('COMMIT');
  assert.equal((await completion).rowCount, 0); assert.equal(await status(), 'open');

  // A failed INSERT rolls the parent changes back in the same transaction.
  await setup.query("UPDATE inquiries SET status='resolved' WHERE id=1");
  const before = await version();
  await assert.rejects(send.query(`INSERT INTO inquiry_messages(id,inquiry_id,sender_id,content) VALUES(1,1,'${guest}','duplicate')`), /duplicate key/);
  assert.equal(await status(), 'resolved'); assert.equal(await version(), before);
  await send.query(`INSERT INTO inquiry_messages(inquiry_id,sender_id,content) VALUES(1,'${admin}','staff reply')`);
  assert.equal(await status(), 'resolved');
  console.log('ADMIN_CHAT_NATIVE_RACES_PASS: both lock orders, stale CAS, rollback, admin reply, publication rerun');
} finally {
  for (const client of clients) await client.end();
  await pg.stop();
  await rm(dir, { recursive: true, force: true });
}
